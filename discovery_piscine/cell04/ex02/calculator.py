#!/usr/bin/env python3
first_number = int(input("Give me the first number: "))
second_number = int(input("Give me the second number: "))
print("Thank you!")

result_add = first_number + second_number
print(str(first_number) + " + " + str(second_number) + " = " + str(result_add))

result_minus = first_number - second_number
print(str(first_number) + " - " + str(second_number) + " = " + str(result_minus))

result_divide = first_number / second_number
print(str(first_number) + " / " + str(second_number) + " = " + str(result_divide))

result_multiply = first_number * second_number
print(str(first_number) + " * " + str(second_number) + " = " + str(result_multiply))
